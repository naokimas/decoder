# =====================================================================
# SI Section S5: Coupled double-well started from the upper state
#
# This script: the cross-transfer matrices with DW replaced
# Feeds      : Figs. S5 and S6
# Produces   : data/dw45_matrices.npz
# Runtime    : about an hour
# See ../README.md for the run order and for where the
# equilibrium data comes from.
# =====================================================================
"""Cross-transfer matrices with DW-upper added as an extra dynamics.

Same protocol as the revision's Figs. 4 and 5 (fig4_fig5_cross_transfer/):
interspersed 41/10 split on the source side, the input and output maps
calibrated on the same 41 target control-parameter values and every cell
scored on the remaining 10, n-RMSE normalized by the target's full range,
and the mean-prediction baseline computed on the same rows with the same
sentinel set.

Two differences, both forced by the new data:
  * the dynamics list has 18 entries, the manuscript's 17 plus DW started
    from the upper well ("DWUP"), inserted next to DW;
  * the DW-up sweeps are the ones generated by generate_dwup.py.

Writes data/dw45_matrices.npz with the 18 x 18 n-RMSE matrix and the
matching baseline matrix for each of the six (decoder, sentinel) panels,
each averaged over the 10 networks.
"""
import os, sys
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS",
           "VECLIB_MAXIMUM_THREADS"):
    os.environ.setdefault(_v, "1")

import importlib.util
import time
from pathlib import Path
import numpy as np
import networkx as nx

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "lib")); import paths  # noqa: E402
EQ = paths.EQ_REVISION        # equilibrium CSVs; see ../README.md
LIB = HERE.parent / "lib"          # shared modules
sys.path.insert(0, str(LIB))
_s = importlib.util.spec_from_file_location(
    "leq", LIB / "load_equilibria.py")
leq = importlib.util.module_from_spec(_s); _s.loader.exec_module(leq)

import pipeline_unified as pu                                   # noqa: E402
import splits                                                   # noqa: E402

DYN = ["SIS", "SIR", "MSIS", "MSIS2", "MSIR", "MSIR2", "DW", "DWUP", "MUT",
       "GEN", "WC", "gLV", "NM", "EUT", "EUT2", "VEG", "VEG2", "LDW"]
DISP = {"MSIS": "MSIS1", "MSIR": "MSIR1", "EUT": "EUT1", "VEG": "VEG1",
        "DWUP": "DW-up"}
PANELS = [("nn", "minc"), ("nn", "qr"), ("nn", "random"),
          ("lin", "minc"), ("lin", "qr"), ("lin", "random")]
REG = {"nn": 0.0, "lin": 0.01}
NETS = leq.NETWORKS            # all 14, now that DW-up covers them


def load_eq(tag, s):
    if s == "DWUP":
        arr = np.loadtxt(
            EQ / "doublewell_upper" / f"{tag}_doublewell_upper_equilibrium_data.csv",
            delimiter=",", skiprows=1)
        return arr[:, 1:]
    return leq.load_eq(tag, s)


def nrmse(pred, true, full_range):
    rmse = float(np.sqrt(np.mean((pred - true) ** 2)))
    return rmse / full_range if full_range > 0 else np.nan


def main():
    n = len(DYN)
    acc = {p: np.zeros((n, n)) for p in PANELS}
    accb = {p: np.zeros((n, n)) for p in PANELS}
    tr, ev = splits.rows_random()
    t0 = time.time()
    for tag in NETS:
        G = nx.read_edgelist(leq.network_file(tag),
                             nodetype=int)
        N = len(G.nodes()); K = int(np.floor(np.log(N)))
        eq = {s: load_eq(tag, s) for s in DYN}
        for s, Y in eq.items():
            assert Y.shape == (51, N), f"{tag}/{s}: {Y.shape}, N={N}"
        rngf = {s: float(eq[s].max() - eq[s].min()) for s in DYN}
        rnd = np.random.default_rng(2026)
        RAND = np.sort(rnd.choice(N, size=K, replace=False))
        for dec, sent in PANELS:
            sidx = {}
            for s in DYN:
                Ytr = eq[s][tr]
                sidx[s] = (pu.qr_pivot_sensors(Ytr, K) if sent == "qr" else
                           pu.min_corr_sensors(Ytr, K) if sent == "minc"
                           else RAND.copy())
            for i, src in enumerate(DYN):
                idx = sidx[src]
                ck = (splits.train_nn(eq[src], idx, REG[dec], tr)
                      if dec == "nn"
                      else splits.fit_linear(eq[src], idx, REG[dec], tr))
                for j, tgt in enumerate(DYN):
                    Yt = eq[tgt]
                    P = splits.predict_calibrated(ck, Yt, dec, tr)
                    acc[(dec, sent)][i, j] += nrmse(P[ev], Yt[ev], rngf[tgt])
                    per = Yt[ev][:, idx].mean(axis=1)
                    B = np.broadcast_to(per[:, None], Yt[ev].shape)
                    accb[(dec, sent)][i, j] += nrmse(B, Yt[ev], rngf[tgt])
        print(f"  {tag}: {time.time()-t0:.0f}s", flush=True)
    out = {}
    for dec, sent in PANELS:
        out[f"M_{dec}_{sent}"] = acc[(dec, sent)] / len(NETS)
        out[f"B_{dec}_{sent}"] = accb[(dec, sent)] / len(NETS)
    np.savez(HERE / "data" / "dw45_matrices.npz",
             dynamics=np.array([DISP.get(d, d) for d in DYN], dtype=object),
             eval_rows=ev, cal_rows=tr, networks=np.array(NETS), **out)
    print(f"  wrote data/dw45_matrices.npz  ({time.time()-t0:.0f}s)")


if __name__ == "__main__":
    main()
